#!/usr/bin/env python3
"""Field one-shot: generate secrets once, emit migrate SQL, init DB, start delivery stack."""
from __future__ import annotations

import base64
import os
import pathlib
import secrets
import socket
import subprocess
import sys
import time

ROOT = pathlib.Path(__file__).resolve().parents[1]
CONFIG = ROOT / "config"
SECRETS = CONFIG / "secrets.env"
DOTENV = ROOT / ".env"
ONCE = CONFIG / "BOOTSTRAP-ONCE.txt"
MIGRATE_SQL = CONFIG / "schema-migrate.sql"
TLS_DIR = CONFIG / "tls"
TLS_CERT = TLS_DIR / "cert.pem"
TLS_KEY = TLS_DIR / "key.pem"
COMPOSE = ROOT / "deploy" / "docker-compose.delivery.yml"
JAR = ROOT / "server" / "kaiwu-praxis-admin-server.jar"
WEB = ROOT / "web" / "dist" / "index.html"
MIGRATE_SCRIPT = ROOT / "scripts" / "migrate-postgres.py"


def token(nbytes: int = 32) -> str:
    return secrets.token_urlsafe(nbytes)


def b64_key(nbytes: int = 32) -> str:
    return base64.b64encode(os.urandom(nbytes)).decode("ascii")


def strong_password() -> str:
    return token(18) + "Aa1"


def load_env_file(path: pathlib.Path) -> dict[str, str]:
    env: dict[str, str] = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, value = line.split("=", 1)
        env[key.strip()] = value
    return env


def sync_dotenv() -> None:
    """Docker Compose auto-loads project .env for ${VAR} interpolation."""
    DOTENV.write_text(SECRETS.read_text(encoding="utf-8"), encoding="utf-8")
    DOTENV.chmod(0o600)


def write_secrets_if_needed() -> bool:
    CONFIG.mkdir(mode=0o700, exist_ok=True)
    if SECRETS.is_file():
        print(f"reusing existing {SECRETS}")
        sync_dotenv()
        return False

    boot_pw = "Sun55kong!"
    maint_pw = strong_password()
    app_pw = strong_password()
    lines = [
        "# Generated by delivery-bootstrap.py — backup offline; do not commit",
        f"POSTGRES_MAINT_PASSWORD={maint_pw}",
        "JDBC_USER=workdsh_app",
        f"JDBC_PASSWORD={app_pw}",
        "JDBC_URL=jdbc:postgresql://postgres:5432/kaiwu_praxis",
        "SPRING_PROFILES_ACTIVE=enterprise-postgres",
        "WORKDSH_ADMIN_WEB_ORIGIN=",
        "WORKDSH_BOOTSTRAP_ADMIN_EMAIL=admin",
        f"WORKDSH_BOOTSTRAP_ADMIN_PASSWORD={boot_pw}",
        "WORKDSH_BOOTSTRAP_REQUIRE_PASSWORD_CHANGE=false",
        f"WORKDSH_SECRETS_ENCRYPTION_KEY={b64_key(32)}",
        f"WORKDSH_SECRETS_SERVICE_KEY={token(32)}",
        "WORKDSH_LICENSE_ENFORCED=true",
    ]
    SECRETS.write_text("\n".join(lines) + "\n", encoding="utf-8")
    SECRETS.chmod(0o600)
    sync_dotenv()
    ONCE.write_text(
        "Bootstrap credentials for 开物Praxis admin.\n\n"
        "username: admin\n"
        f"password: {boot_pw}\n\n"
        f"Also backup offline: {SECRETS}\n"
        "(encryption key, service key, DB passwords)\n",
        encoding="utf-8",
    )
    ONCE.chmod(0o600)
    print(f"wrote {SECRETS}")
    print(f"wrote {ONCE}")
    print(f"wrote {DOTENV} (for docker compose)")
    return True


def emit_migrate_sql() -> None:
    if not MIGRATE_SCRIPT.is_file():
        raise SystemExit(f"missing {MIGRATE_SCRIPT}")
    out = subprocess.check_output(
        [sys.executable, str(MIGRATE_SCRIPT), "--emit-sql"],
        cwd=str(ROOT),
    )
    MIGRATE_SQL.write_bytes(out)
    MIGRATE_SQL.chmod(0o600)
    print(f"wrote {MIGRATE_SQL} ({len(out)} bytes)")


def detect_lan_ipv4() -> list[str]:
    found: set[str] = set()
    try:
        with socket.socket(socket.AF_INET, socket.SOCK_DGRAM) as sock:
            sock.connect(("8.8.8.8", 80))
            ip = sock.getsockname()[0]
            if ip and not ip.startswith("127."):
                found.add(ip)
    except OSError:
        pass
    try:
        for info in socket.getaddrinfo(socket.gethostname(), None, socket.AF_INET):
            ip = info[4][0]
            if ip and not ip.startswith("127."):
                found.add(ip)
    except OSError:
        pass
    extra = os.environ.get("DELIVERY_HOST", "").strip()
    if extra and extra not in ("localhost", "127.0.0.1"):
        found.add(extra)
    return sorted(found)


def ensure_self_signed_tls() -> None:
    """Self-signed cert with localhost + detected LAN IPs (and optional DELIVERY_HOST)."""
    if TLS_CERT.is_file() and TLS_KEY.is_file():
        print(f"reusing existing TLS material in {TLS_DIR}")
        return
    TLS_DIR.mkdir(mode=0o700, exist_ok=True)
    san = ["DNS:localhost", "DNS:kaiwu-praxis-admin", "IP:127.0.0.1"]
    for host in detect_lan_ipv4():
        if host.replace(".", "").isdigit() or host.count(":") >= 2:
            entry = f"IP:{host}"
        else:
            entry = f"DNS:{host}"
        if entry not in san:
            san.append(entry)
    san_arg = "subjectAltName=" + ",".join(san)
    subprocess.run(
        [
            "openssl",
            "req",
            "-x509",
            "-newkey",
            "rsa:2048",
            "-sha256",
            "-days",
            "825",
            "-nodes",
            "-keyout",
            str(TLS_KEY),
            "-out",
            str(TLS_CERT),
            "-subj",
            "/CN=kaiwu-praxis-admin",
            "-addext",
            san_arg,
        ],
        check=True,
        capture_output=True,
    )
    TLS_KEY.chmod(0o600)
    TLS_CERT.chmod(0o644)
    print(f"wrote self-signed TLS cert ({san_arg})")


def compose_env() -> dict[str, str]:
    env = os.environ.copy()
    env.update(load_env_file(SECRETS))
    return env


def compose_cmd(*args: str) -> list[str]:
    return [
        "docker",
        "compose",
        "-f",
        str(COMPOSE),
        "--project-directory",
        str(ROOT),
        *args,
    ]


def wait_postgres_healthy(timeout_sec: int = 120) -> None:
    deadline = time.time() + timeout_sec
    while time.time() < deadline:
        proc = subprocess.run(
            compose_cmd("ps", "--status", "running", "-q", "postgres"),
            cwd=str(ROOT),
            env=compose_env(),
            capture_output=True,
            text=True,
        )
        cid = (proc.stdout or "").strip()
        if cid:
            inspect = subprocess.run(
                ["docker", "inspect", "-f", "{{.State.Health.Status}}", cid],
                capture_output=True,
                text=True,
            )
            if inspect.stdout.strip() == "healthy":
                print("postgres is healthy")
                return
        time.sleep(2)
    raise SystemExit("postgres did not become healthy in time")


def run_db_init() -> None:
    print("running db-init (migrate + grants)...")
    subprocess.run(
        compose_cmd("--profile", "init", "run", "--rm", "db-init"),
        check=True,
        env=compose_env(),
        cwd=str(ROOT),
    )


def compose_up_stack() -> None:
    # postgres first → init → admin+caddy (db-init is profile-gated, not on every up)
    subprocess.run(
        compose_cmd("up", "-d", "--remove-orphans", "postgres"),
        check=True,
        env=compose_env(),
        cwd=str(ROOT),
    )
    wait_postgres_healthy()
    run_db_init()
    subprocess.run(
        compose_cmd("up", "-d", "--remove-orphans", "admin", "caddy"),
        check=True,
        env=compose_env(),
        cwd=str(ROOT),
    )


def main() -> int:
    if not COMPOSE.is_file():
        raise SystemExit(f"missing {COMPOSE}")
    if not JAR.is_file():
        raise SystemExit(
            f"missing {JAR}\nInstall a candidate package first (or build the server JAR)."
        )
    if not WEB.is_file():
        raise SystemExit(f"missing {WEB}\nBuild admin Web (web/dist) before bootstrap.")
    for cmd in (("docker", "version"), ("docker", "compose", "version")):
        try:
            subprocess.run(cmd, check=True, capture_output=True)
        except (OSError, subprocess.CalledProcessError) as exc:
            raise SystemExit(f"Docker is required ({' '.join(cmd)}): {exc}") from exc

    write_secrets_if_needed()
    ensure_self_signed_tls()
    emit_migrate_sql()
    compose_up_stack()
    print()
    print("Delivery stack started.")
    print("  URL:  https://<this-host>/  (accept the self-signed certificate warning)")
    print(f"  Login: admin / Sun55kong!  (see also {ONCE})")
    print(f"  Secrets backup: {SECRETS}")
    print("Still required after install: upload license; Desktop joint debugging.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
